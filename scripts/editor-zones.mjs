// Vývojová kontrola: kreslení zóny po zemi, chytré výchozí hodnoty, úchopy rozměru zóny.
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const url = process.argv[2] ?? 'http://localhost:5173/';
const shotDir = process.argv[3];
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 1366, height: 768 } });
p.on('pageerror', (e) => console.log('[pageerror]', e.message));
await p.goto(`${url}?editor&q=low`);
await p.waitForFunction(() => window.__pf && window.__pf.editor, null, { timeout: 240000 });
await p.waitForTimeout(1500);
const ok = (c, m) => { console.log(c ? 'OK  ' : 'FAIL', m); if (!c) process.exitCode = 1; };
await p.evaluate(() => window.__pf.openDoc(window.__pf.streetTemplate(), false));
await p.waitForTimeout(3000);
await p.evaluate(() => { const a = window.__pf; a.editor.restoreCamera({ pos: new a.camera.position.constructor(0, 45, 50), yaw: 0, pitch: -1.1, fov: 60 }); });
await p.keyboard.press('5');
await p.waitForTimeout(500);
const n0 = await p.evaluate(() => window.__pf.ed.doc.zones.length);
await p.getByRole('button', { name: '✏ Zakázaná zóna' }).click();
const r = await p.evaluate(() => document.querySelector('#view').getBoundingClientRect().toJSON());
const x0 = r.left + r.width * 0.42, y0 = r.top + r.height * 0.45;
await p.mouse.move(x0, y0);
await p.mouse.down();
await p.mouse.move(x0 + 80, y0 + 40, { steps: 6 });
await p.mouse.move(x0 + 160, y0 + 90, { steps: 6 });
await p.waitForTimeout(300);
if (shotDir) await p.screenshot({ path: `${shotDir}/zone-draw.png` });
await p.mouse.up();
await p.waitForTimeout(600);
const z = await p.evaluate(() => { const d = window.__pf.ed.doc; const z = d.zones.at(-1); return { n: d.zones.length, z, inSc: d.scenarios.every((s) => s.zoneIds.includes(z.id)), sel: [...window.__pf.editor.selection] }; });
ok(z.n === n0 + 1, `nakreslená zóna přidána (${n0} → ${z.n}), rozměr ${(z.z.halfExtents[0] * 2).toFixed(1)} × ${(z.z.halfExtents[2] * 2).toFixed(1)} × ${(z.z.halfExtents[1] * 2).toFixed(1)} m, týmy ${z.z.appliesTo}`);
ok(z.inSc, 'zóna je zapnutá ve všech scénářích');
ok(z.sel[0] === `zn:${z.z.id}`, 'nová zóna je vybraná');
await p.waitForTimeout(500);
if (shotDir) await p.screenshot({ path: `${shotDir}/zone-selected.png` });
// Tažení úchopu +X: šířka roste, levá stěna stojí.
const h = await p.evaluate(() => {
  const e = window.__pf.editor;
  const c = e.handles.children.find((m) => m.userData.handle.kind === 'zone' && m.userData.handle.axis === 'x' && m.userData.handle.sign === 1);
  const v = c.position.clone().project(window.__pf.camera);
  const rc = document.querySelector('#view').getBoundingClientRect();
  return { x: rc.left + (v.x + 1) / 2 * rc.width, y: rc.top + (1 - v.y) / 2 * rc.height };
});
await p.mouse.move(h.x, h.y);
await p.mouse.down();
await p.mouse.move(h.x + 60, h.y, { steps: 8 });
await p.mouse.up();
await p.waitForTimeout(500);
const z2 = await p.evaluate((id) => window.__pf.ed.doc.zones.find((q) => q.id === id), z.z.id);
const left0 = z.z.center[0] - z.z.halfExtents[0], left1 = z2.center[0] - z2.halfExtents[0];
ok(z2.halfExtents[0] > z.z.halfExtents[0] + 1, `úchop rozšířil zónu: ${(z.z.halfExtents[0] * 2).toFixed(1)} → ${(z2.halfExtents[0] * 2).toFixed(1)} m`);
ok(Math.abs(left0 - left1) < 0.01, `protilehlá stěna zůstala (${left0.toFixed(2)} / ${left1.toFixed(2)})`);
await p.keyboard.press('Control+z');
await p.waitForTimeout(300);
const z3 = await p.evaluate((id) => window.__pf.ed.doc.zones.find((q) => q.id === id), z.z.id);
ok(Math.abs(z3.halfExtents[0] - z.z.halfExtents[0]) < 1e-6, 'Ctrl+Z vrátí rozměr');
if (shotDir) await p.screenshot({ path: `${shotDir}/zone-inspector.png` });
// Esc ruší kreslení.
await p.getByRole('button', { name: '✏ Hranice mapy' }).click();
await p.keyboard.press('Escape');
await p.mouse.click(x0, y0);
await p.waitForTimeout(300);
ok((await p.evaluate(() => window.__pf.ed.doc.zones.length)) === z.n, 'Esc kreslení zruší');
await b.close();
